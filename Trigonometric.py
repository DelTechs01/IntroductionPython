#Sin(x), Cos(x), Tan(x)
import math
x = 30
print("Sin(30) :", math.sin(x))
print("Cos(30) :", math.cos(x))
print("Tan(30) :", math.tan(x))

#Trigonometric inverse functions
#Asin(x), Acos(x), Atan(x)
import math
x = 0.5
print("Asin(0.5) :", math.asin(x))
print("Acos(0.5) :", math.acos(x))
print("Atan(0.5) :", math.atan(x))
print("Atan2(0.5,1) :", math.atan2(0.5,1))

#Sinh(x), Cosh(x), Tanh(x)
import math
x = 30
print("Sinh(30) :", math.sinh(x))
print("Cosh(30) :", math.cosh(x))
print("Tanh(30) :", math.tanh(x))

#Trigonometric Misc Functions
#Radians(x), Degrees(x)
